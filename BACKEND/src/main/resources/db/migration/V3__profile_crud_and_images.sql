-- V3 adds gallery metadata and a separate binary table so profile list queries never fetch image bytes.
CREATE TABLE profile_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    display_order INTEGER NOT NULL,
    source_url VARCHAR(1000),
    content_type VARCHAR(100),
    size_bytes BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_profile_image_source CHECK (source_url IS NOT NULL OR content_type IS NOT NULL)
);

-- The image payload has its own table and cascade, separate from the profile/gallery metadata.
CREATE TABLE profile_image_blobs (
    image_id BIGINT PRIMARY KEY REFERENCES profile_images(id) ON DELETE CASCADE,
    data BYTEA NOT NULL
);

CREATE INDEX idx_profile_images_profile_order ON profile_images(profile_id, display_order);


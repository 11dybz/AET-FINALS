CREATE TABLE messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL REFERENCES visitor_sessions(id),
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id),
    sender VARCHAR(255) NOT NULL CHECK (sender IN ('visitor', 'member')),
    body VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_messages_session_profile_id ON messages(session_id, profile_id, id);

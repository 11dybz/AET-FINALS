CREATE TABLE video_calls (
    id VARCHAR(255) PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL REFERENCES visitor_sessions(id) ON DELETE CASCADE,
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    state VARCHAR(32) NOT NULL,
    offer VARCHAR(16000) NOT NULL,
    answer VARCHAR(16000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    visitor_heartbeat TIMESTAMP WITH TIME ZONE NOT NULL,
    team_heartbeat TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_calls_session_state ON video_calls(session_id, state);
CREATE INDEX idx_calls_profile_state ON video_calls(profile_id, state);
CREATE TABLE call_signals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id VARCHAR(255) NOT NULL REFERENCES video_calls(id) ON DELETE CASCADE,
    sender VARCHAR(16) NOT NULL,
    payload VARCHAR(4000) NOT NULL
);
CREATE INDEX idx_call_signals_call ON call_signals(call_id, id);
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL REFERENCES visitor_sessions(id) ON DELETE CASCADE,
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id) ON DELETE CASCADE,
    kind VARCHAR(32) NOT NULL,
    body VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_notifications_session ON notifications(session_id, id);

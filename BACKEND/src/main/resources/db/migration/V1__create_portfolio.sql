CREATE TABLE profiles (
    id VARCHAR(255) PRIMARY KEY,
    persona VARCHAR(255), name VARCHAR(255), age INTEGER NOT NULL,
    location VARCHAR(255), role VARCHAR(255), image VARCHAR(1000),
    verified BOOLEAN NOT NULL, match_percentage VARCHAR(255), bio VARCHAR(2000),
    full_bio VARCHAR(4000), github VARCHAR(255), linkedin VARCHAR(255), email VARCHAR(255),
    display_order INTEGER NOT NULL
);
CREATE TABLE profile_skills (
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id),
    display_order INTEGER NOT NULL, skill VARCHAR(255),
    PRIMARY KEY (profile_id, display_order)
);
CREATE TABLE profile_highlights (
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id),
    display_order INTEGER NOT NULL, highlight VARCHAR(1000),
    PRIMARY KEY (profile_id, display_order)
);
CREATE TABLE projects (
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id),
    display_order INTEGER NOT NULL, title VARCHAR(255), description VARCHAR(2000),
    PRIMARY KEY (profile_id, display_order)
);
CREATE TABLE visitor_sessions (
    id VARCHAR(255) PRIMARY KEY, expires_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_session_expiry ON visitor_sessions(expires_at);
CREATE TABLE swipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) NOT NULL REFERENCES visitor_sessions(id),
    profile_id VARCHAR(255) NOT NULL REFERENCES profiles(id),
    action VARCHAR(255) NOT NULL CHECK (action IN ('pass', 'like', 'super_like')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_swipe_session_profile UNIQUE (session_id, profile_id)
);
